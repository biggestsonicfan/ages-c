#!/usr/bin/env python3
"""Write ages_all.h: every fn/*.h (Fighting Vipers) and vf2/*.h (Virtua
Fighter 2), and the per-set patch tables ages.h wants (ages_sets[]).
Only functions that are defined go in a table, so a half-converted tree
builds. Usage: gen_all.py [out_path]  (default: ages_all.h beside this file)."""
import os, re, sys, glob
D = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(D, 'ages_all.h')
fn_files = sorted(glob.glob(os.path.join(D, 'fn', '*.h'))) + sorted(glob.glob(os.path.join(D, 'vf2', '*.h')))
defined = []
for f in fn_files:
    for m in re.finditer(r'^static\s+uint32_t\s+(afn_\w+)\s*\(\s*int\s+entry\s*\)\s*\{', open(f).read(), re.M):
        defined.append(m.group(1))
# The patch sites come from ages-decomp's FV/FN/INDEX.md (the decomp/ submodule):
# | EXT | native | name | i960 sites | arcade name | lines | file |
INDEX = os.path.join(D, 'decomp', 'FV', 'FN', 'INDEX.md')
if not os.path.exists(INDEX):
    sys.exit('gen_all.py: no %s; run: git submodule update --init decomp' % INDEX)
# nohook.txt: roots that are defined (other C calls them) but left to the i960
# at their own patch site, one per line: name, then why.
NOHOOK = os.path.join(D, 'nohook.txt')
nohook = set()
if os.path.exists(NOHOOK):
    nohook = {l.split()[0] for l in open(NOHOOK) if l.strip() and not l.startswith('#')}
patches = []
for l in open(INDEX):
    m = re.match(r'\| ([0-9a-f]{2}) \| [0-9a-f]{8} \| (\w+) \| ([0-9a-f ,]+) \|', l)
    if m and 'afn_' + m.group(2) in defined and m.group(2) not in nohook:
        for site in re.findall(r'[0-9a-f]+', m.group(3)):
            patches.append((int(site, 16), m.group(2), m.group(1)))
# VF2's sites come from decomp/VF2/patches.tsv (its INDEX.md shortens set_obj's
# 140): i960, word0, word1, "ext NN", the PS2 function. The C for
# sysCopPatchCalcUnitMat is afn_vf2_calc_unit_mat: the arcade's snake-case name.
def vf2_name(ps2):
    for p in ('sysCopPatch', 'sysCop'):
        if ps2.startswith(p):
            return re.sub(r'(?<!^)([A-Z])', r'_\1', ps2[len(p):]).lower()
    return None
vf2 = []
for l in open(os.path.join(D, 'decomp', 'VF2', 'patches.tsv')):
    c = l.rstrip('\n').split('\t')
    if len(c) < 5 or not c[3].startswith('ext '):
        continue
    n = vf2_name(c[4])
    if n and 'afn_vf2_' + n in defined and 'vf2_' + n not in nohook:
        vf2.append((int(c[0], 16), 'vf2_' + n, n, c[3][4:]))
L = ['/* Generated by gen_all.py. */', '#pragma once']
# Prototypes first, so the files can call each other in any order.
L += ['static uint32_t %s(int entry);' % n for n in defined]
L += ['#include "%s"' % os.path.relpath(f, D) for f in fn_files]
def table(name, rows):
    L.append('static const gems_trap_t %s[] = {' % name)
    L.extend(['    { 0x%06X, afn_%s, "%s" },   /* EXT %s */' % r for r in rows] or ['    { 0, 0, 0 },'])
    L.append('};')
table('ages_patches_fvipers', [(a, n, n, e) for a, n, e in patches])
table('ages_patches_vf2', vf2)
L.append('static const ages_set_t ages_sets[] = {')
L.append('    { "fvipers", ages_patches_fvipers, %d },' % len(patches))
L.append('    { "vf2",     ages_patches_vf2,     %d },' % len(vf2))
L.append('};')
L.append('static const size_t ages_set_count = 2;')
text = '\n'.join(L) + '\n'
# Left alone when nothing changed, so a build that runs this every time stays incremental.
if not os.path.exists(out) or open(out).read() != text:
    open(out, 'w').write(text)
print('%s: %d fvipers patches, %d vf2' % (out, len(patches), len(vf2)))
