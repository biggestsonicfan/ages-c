#!/usr/bin/env python3
"""Write ages_all.h: every fn/*.h, and the patch table ages.h wants.
Only functions that are defined go in the table, so a half-converted tree
builds. Usage: gen_all.py [out_path]  (default: ages_all.h beside this file)."""
import os, re, sys, glob
D = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(D, 'ages_all.h')
fn_files = sorted(glob.glob(os.path.join(D, 'fn', '*.h')))
defined = []
for f in fn_files:
    for m in re.finditer(r'^static\s+uint32_t\s+(afn_\w+)\s*\(\s*int\s+entry\s*\)\s*\{', open(f).read(), re.M):
        defined.append(m.group(1))
# The patch sites come from ages-decomp's FV/FN/INDEX.md (the decomp/ submodule):
# | EXT | native | name | i960 sites | arcade name | lines | file |
INDEX = os.path.join(D, 'decomp', 'FV', 'FN', 'INDEX.md')
if not os.path.exists(INDEX):
    sys.exit('gen_all.py: no %s; run: git submodule update --init decomp' % INDEX)
# nohook.txt: roots that are defined (other C calls them) but left to the i960
# at their own patch site, one per line: name, then why.
NOHOOK = os.path.join(D, 'nohook.txt')
nohook = set()
if os.path.exists(NOHOOK):
    nohook = {l.split()[0] for l in open(NOHOOK) if l.strip() and not l.startswith('#')}
patches = []
for l in open(INDEX):
    m = re.match(r'\| ([0-9a-f]{2}) \| [0-9a-f]{8} \| (\w+) \| ([0-9a-f ,]+) \|', l)
    if m and 'afn_' + m.group(2) in defined and m.group(2) not in nohook:
        for site in re.findall(r'[0-9a-f]+', m.group(3)):
            patches.append((int(site, 16), m.group(2), m.group(1)))
L = ['/* Generated by gen_all.py. */', '#pragma once']
# Prototypes first, so the files can call each other in any order.
L += ['static uint32_t %s(int entry);' % n for n in defined]
L += ['#include "%s"' % os.path.relpath(f, D) for f in fn_files]
L.append('static const gems_trap_t ages_patches[] = {')
L += ['    { 0x%06X, afn_%s, "%s" },   /* EXT %s */' % (a, n, n, e) for a, n, e in patches] or ['    { 0, 0, 0 },']
L.append('};')
L.append('static const size_t ages_patch_count = %d;' % len(patches))
text = '\n'.join(L) + '\n'
# Left alone when nothing changed, so a build that runs this every time stays incremental.
if not os.path.exists(out) or open(out).read() != text:
    open(out, 'w').write(text)
print('%s: %d patches' % (out, len(patches)))
